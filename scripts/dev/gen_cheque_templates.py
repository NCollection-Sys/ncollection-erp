#!/usr/bin/env python3
"""Generate the three initial cheque templates (data XML) and their SCHEMATIC reference images from ONE layout table.

Run inside the Odoo container (it needs Pillow), from the repository root:
    docker compose exec -T odoo python3 - < scripts/dev/gen_cheque_templates.py

WHAT THE NUMBERS ARE. Each bank layout below was read, as FRACTIONS of the page, off a photograph of that bank's cheque
(field order, relative position and size of the date, payee, amount-in-words and amount areas). The physical sizes are
PROVISIONAL: they are derived from the proportions of the photographs, which carry no scale and may be cropped or taken
at an angle. Every template therefore ships with ``dimensions_confirmed = False`` and the module shows a banner until
someone measures a real cheque and confirms it. Nothing here is a measured coordinate.

WHAT THE IMAGES ARE. The reference images are drawn here from the same table: pale paper, labelled boxes where the
printable areas are, a hatched block where the bank's pre-printed logo and security artwork sit, and a MICR band
that is left blank. They contain NO real logo, name, signature, account number, IBAN, cheque number, QR code or
MICR digits, and none of that is read from the photographs into the repository.
"""
