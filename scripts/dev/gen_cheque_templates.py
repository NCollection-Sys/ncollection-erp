def boxes(bank):
    out = {}
    for key, (fx, fy, fw, fh) in bank['fields'].items():
        out[key] = tuple(round(v, 1) for v in (fx * bank['width'], fy * bank['height'], fw * bank['width'],
                                               fh * bank['height']))
    return out


def field_xml(bank_id, key, box, extra, sequence, visible=True):
    x, y, w, h = box
    lines = ['    <record id="%s_%s" model="ncollection.cheque.template.field">' % (bank_id, key),
             '        <field name="template_id" ref="%s"/>' % bank_id,
             '        <field name="sequence">%d</field>' % sequence,
             '        <field name="key">%s</field>' % key,
             '        <field name="x_mm">%s</field>' % x, '        <field name="y_mm">%s</field>' % y,
             '        <field name="width_mm">%s</field>' % w, '        <field name="height_mm">%s</field>' % h]
    for name, value in extra.items():
        lines.append('        <field name="%s">%s</field>' % (name, value))
    if not visible:
        lines.append('        <field name="visible" eval="False"/>')
    lines.append('    </record>')
    return '\n'.join(lines)


def write_xml():
    parts = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by scripts/dev/gen_cheque_templates.py - edit the table there, not this file. -->',
             '<!-- noupdate: a customer\'s calibration of a template must survive a module upgrade. -->',
             '<odoo noupdate="1">', '']
    for bank in BANKS:
        fmt = bank['format']
        parts += [
            '    <record id="%s" model="ncollection.cheque.template">' % bank['id'],
            '        <field name="name">%s</field>' % bank['name'],
            '        <field name="bank_name">%s</field>' % bank['bank'],
            '        <field name="sequence">%d</field>' % bank['sequence'],
            '        <field name="width_mm">%s</field>' % bank['width'],
            '        <field name="height_mm">%s</field>' % bank['height'],
            '        <field name="dimensions_confirmed" eval="False"/>',
            '        <field name="currency_id" ref="base.AED"/>',
            '        <field name="printer_profile_id" ref="printer_profile_default"/>',
            '        <field name="description">Initial template. The size and the field positions are PROVISIONAL, '
            'read from a photograph of the cheque layout, and must be calibrated against a physical cheque before '
            'real use.</field>',
            '        <field name="reference_image" type="base64" file="ncollection_cheque_print/static/src/img/%s"/>'
            % bank['image'],
            '    </record>', '']
        layout = boxes(bank)
        parts.append(field_xml(bank['id'], 'payment_date', layout['payment_date'],
                               {'date_format': fmt['date_format']}, 10))
        payee_extra = {'fit': 'wrap', 'max_lines': fmt['payee_wrap']} if fmt.get('payee_wrap') else {}
        parts.append(field_xml(bank['id'], 'payee', layout['payee'], payee_extra, 20))
        words_extra = {'fit': 'wrap', 'max_lines': fmt['words_wrap'], 'case': fmt['words_case'], 'size_pt': 10.0}
        if fmt.get('words_chars'):
            words_extra.update({'prefix': fmt['words_chars'], 'suffix': fmt['words_chars']})
        parts.append(field_xml(bank['id'], 'amount_words', layout['amount_words'], words_extra, 30))
        amount_extra = {'align': 'right', 'bold': 'True', 'size_pt': 12.0}
        if fmt.get('amount_wrap_chars'):
            amount_extra.update({'prefix': fmt['amount_wrap_chars'], 'suffix': fmt['amount_wrap_chars']})
        amount_extra['bold'] = 'True'
        parts.append(field_xml(bank['id'], 'amount', layout['amount'], amount_extra, 40))
        parts.append(field_xml(bank['id'], 'reference', layout['reference'], {'size_pt': 9.0}, 50, visible=False))
        parts.append('')
    parts.append('</odoo>')
    text = '\n'.join(parts).replace('<field name="bold">True</field>', '<field name="bold" eval="True"/>')
    with open(OUT_XML, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text + '\n')


def font(size):
    for path in ('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',):
        if os.path.exists(path):
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def draw_image(bank):
    width_px = 1600
    height_px = int(width_px * bank['height'] / bank['width'])
    image = Image.new('RGB', (width_px, height_px), (245, 246, 248))
    draw = ImageDraw.Draw(image)
    draw.rectangle((2, 2, width_px - 3, height_px - 3), outline=(170, 176, 186), width=3)
    # the pre-printed bank artwork: a hatched block, deliberately anonymous
    block = (int(width_px * 0.03), int(height_px * 0.05), int(width_px * 0.24), int(height_px * 0.22))
    draw.rectangle(block, fill=(232, 235, 240), outline=(190, 196, 206), width=2)
    for offset in range(-block[3], block[2] - block[0], 22):
        draw.line((block[0] + offset, block[3], block[0] + offset + (block[3] - block[1]), block[1]),
                  fill=(214, 219, 227), width=2)
    draw.text((block[0] + 12, block[1] + 10), 'PRE-PRINTED BANK ARTWORK', fill=(120, 128, 140), font=font(22))
    draw.text((int(width_px * 0.03), int(height_px * 0.25)), bank['name'].upper() + ' LAYOUT (SCHEMATIC)',
              fill=(120, 128, 140), font=font(24))
    labels = {'payment_date': 'DATE', 'payee': 'PAYEE', 'amount_words': 'AMOUNT IN WORDS', 'amount': 'AMOUNT',
              'reference': 'REFERENCE (optional)'}
    for key, (fx, fy, fw, fh) in bank['fields'].items():
        box = (fx * width_px, fy * height_px, (fx + fw) * width_px, (fy + fh) * height_px)
        draw.rectangle(box, outline=(120, 150, 190), width=2)
        draw.line((box[0], box[3], box[2], box[3]), fill=(120, 150, 190), width=3)
        draw.text((box[0] + 6, box[1] + 3), labels[key], fill=(150, 165, 190), font=font(20))
    sign = (int(width_px * 0.68), int(height_px * 0.74), int(width_px * 0.96), int(height_px * 0.86))
    draw.line((sign[0], sign[3], sign[2], sign[3]), fill=(150, 156, 168), width=3)
    draw.text((sign[0], sign[3] + 6), 'SIGNATURE (by hand)', fill=(150, 156, 168), font=font(20))
    micr = (int(width_px * 0.04), int(height_px * 0.90), int(width_px * 0.96), int(height_px * 0.97))
    draw.rectangle(micr, fill=(238, 240, 244), outline=(200, 205, 214))
    draw.text((micr[0] + 10, micr[1] + 8), 'MICR LINE - PRE-PRINTED, NEVER GENERATED', fill=(150, 156, 168),
              font=font(20))
    draw.text((width_px - 560, int(height_px * 0.60)), 'Schematic reference - not a real cheque',
              fill=(170, 176, 186), font=font(20))
    image.save(os.path.join(OUT_IMG, bank['image']), optimize=True)


