# -*- coding: utf-8 -*-
"""The application side of the A-Cube hard stop (sandbox pack step S04): OUR identifiers are deterministic.

Whether A-Cube keeps our ``cbc:UUID`` can only be proven on its sandbox. Proven here is everything that does not
depend on A-Cube: one UUID per revision, never regenerated by a re-preparation, a regenerated XML or a retry; the
idempotency key and correlation id stable across retries; the provider document id stored separately; and two
documents never sharing a UUID."""

import re
from datetime import timedelta

from odoo import fields
from odoo.tests import tagged

from odoo.addons.queue_job.tests.common import trap_jobs

from .test_transport import TransportCase


def _xml_uuid(record):
    return re.search(rb'<cbc:UUID>([^<]+)</cbc:UUID>', record.xml_attachment_id.raw).group(1).decode()


@tagged('post_install', '-at_install')
class TestUuidIdentity(TransportCase):

    def test_one_uuid_per_revision_survives_re_preparation_and_xml_regeneration(self):
        record = self._einvoice()
        record.action_prepare()
        first = record.uuid
        self.assertTrue(first)
        record.action_generate_xml()
        self.assertEqual(_xml_uuid(record), first)
        record.action_prepare()  # back to draft, prepared again: the identity is kept
        record.action_generate_xml()
        self.assertEqual((record.uuid, _xml_uuid(record)), (first, first))

    def test_retries_keep_uuid_idempotency_key_and_correlation_id(self):
        record = self._validated_einvoice()
        uuid = record.uuid
        self.adapter.fail_next = 'transient'
        submission, _trap = self._submit(record)
        key, correlation = submission.idempotency_key, submission.correlation_id
        self.assertEqual(self._run(submission), 'retry')
        submission.sudo().write({'next_attempt_at': fields.Datetime.now() - timedelta(seconds=1)})
        self.assertEqual(self._run(submission), 'accepted')
        self.assertEqual((record.uuid, submission.idempotency_key, submission.correlation_id),
                         (uuid, key, correlation))
        self.assertEqual(len(record.sudo().submission_ids), 1, 'one logical submission')

    def test_the_provider_id_is_a_separate_identifier(self):
        record = self._validated_einvoice()
        submission, _trap = self._submit(record)
        self._run(submission)
        self.assertTrue(record.asp_reference)
        self.assertNotEqual(record.asp_reference, record.uuid)
        self.assertEqual(record.asp_reference, submission.asp_document_id)

    def test_two_documents_never_share_a_uuid(self):
        first, second = self._validated_einvoice(), self._validated_einvoice()
        self.assertNotEqual(first.uuid, second.uuid)
        with trap_jobs():
            first.action_submit()
            second.action_submit()
        self.assertNotEqual(first.current_submission_id.idempotency_key, second.current_submission_id.idempotency_key)
