# -*- coding: utf-8 -*-
"""Custom print title of ONE invoice.

Presentation only: two plain fields on ``account.move`` and a template that prints them instead of the stock
"Invoice" / "Credit Note" / ... heading. Nothing here touches the number, the state, posting, journal items or
any accounting field, and the stock title stays the default (switch off, or leave empty, and the document
prints exactly as before). The title belongs to the individual document: it is not a company or journal
setting, and it is not copied to a duplicated invoice or to its credit note.
"""
from odoo import api, fields, models
from odoo.exceptions import ValidationError

NC_PRINT_TITLE_MAX = 80


class AccountMove(models.Model):
    _inherit = ['account.move', 'nc.duplicate.mixin', 'nc.partner.roles.mixin', 'nc.attachment.mixin',
                'nc.document.print.mixin']
    _name = 'account.move'

    nc_print_title_enabled = fields.Boolean(
        string='Custom print title', copy=False, default=False,
        help="Print the title below instead of the standard one (Invoice, Credit Note, ...) on this document only.")
    nc_print_title = fields.Char(
        string='Custom title', copy=False,
        help="e.g. TAX INVOICE or فاتورة ضريبية. The document number is still printed after it.")

    @api.constrains('nc_print_title_enabled', 'nc_print_title')
    def _check_nc_print_title(self):
        for move in self:
            if not move.nc_print_title_enabled:
                continue
            title = (move.nc_print_title or '').strip()
            if not title:
                raise ValidationError(self.env._("Enter the custom print title, or switch the option off."))
            if len(title) > NC_PRINT_TITLE_MAX or '\n' in title or '\r' in title:
                raise ValidationError(self.env._(
                    "The custom print title must be one line of at most %(max)s characters.", max=NC_PRINT_TITLE_MAX))

    @api.onchange('nc_print_title_enabled')
    def _onchange_nc_print_title_enabled(self):
        if not self.nc_print_title_enabled:
            self.nc_print_title = False

    def _nc_document_title(self):
        """The custom title when this document has one switched on, else False (the stock heading prints)."""
        self.ensure_one()
        title = (self.nc_print_title or '').strip()
        return title if self.nc_print_title_enabled and title else False

    # ------------------------------------------------------------------ Duplicate
    nc_can_duplicate = fields.Boolean(compute='_compute_nc_can_duplicate', string='Can be duplicated')

    @api.depends('move_type', 'origin_payment_id', 'statement_line_id')
    def _compute_nc_can_duplicate(self):
        for move in self:
            move.nc_can_duplicate = not move._nc_duplicate_blocker()

    def _nc_duplicate_blocker(self):
        """Invoices, bills, credit notes, receipts and hand-made journal entries can be duplicated. An entry that
        another document generated (a payment's, a bank statement line's) cannot: a copy of it would be an orphan
        that looks like that document's posting."""
        if self.move_type == 'entry' and (self.origin_payment_id or self.statement_line_id):
            return self.env._(
                "This entry was generated by a payment or a bank statement line and cannot be duplicated.")
        return super()._nc_duplicate_blocker()

    # ------------------------------------------------------------------ Preview = Print (one rendering path)
    # Odoo's Preview opens the CUSTOMER PORTAL page (its own request, language and proforma rules) while Print renders
    # the report with the user's context, and Print marks every invoice that has no stored PDF as a PRO-FORMA, even a
    # posted one. Two paths, two documents. Here both go through ONE method: the same report, the same context, the
    # report engine call that Print makes (View serves it inline, in a new tab: ncollection_core's
    # /ncollection/document/view endpoint, never a second rendering).
    def _nc_print_report(self):
        """The report action Print uses (the default invoice PDF template for this document)."""
        self.ensure_one()
        return self.env['account.move.send']._get_default_pdf_report_id(self)

    def _nc_print_context(self):
        """The context both Preview and Print render with: the canonical invoice report, never the pro-forma flag.

        Odoo's header Print marks an invoice without a stored PDF as a pro-forma, while the same report printed from
        the gear menu (the only Print a draft has) carries no flag at all; a posted invoice would read "Proforma" and
        a draft's Preview would read "Draft Proforma Invoice" against a printed "Draft Invoice". The flag is set
        explicitly to False so the document is the same whichever way it is opened: "Invoice" when posted, "Draft
        Invoice" when draft. The separate pro-forma reports (e.g. the sale order's Pro-Forma Invoice) are untouched."""
        self.ensure_one()
        return {'proforma_invoice': False}

    def action_print_pdf(self):
        self.ensure_one()
        report = self._nc_print_report()
        action = report.with_context(**self._nc_print_context()).report_action(self.id, config=False)
        return self._get_action_with_base_document_layout_configurator(action)

    def preview_invoice(self):
        """The same PDF Print produces, opened inline (a new tab), not a different portal rendering of it."""
        return self.action_nc_view()

    def action_nc_print(self):
        """Print from a list row is the header Print (the document-layout configurator first, when none is chosen)."""
        return self.action_print_pdf()

    # ------------------------------------------------------------------ Customer / Vendor tags beside the partner
    nc_partner_is_customer = fields.Boolean(related='partner_id.nc_is_customer', string='Partner is a customer')
    nc_partner_is_vendor = fields.Boolean(related='partner_id.nc_is_vendor', string='Partner is a vendor')
