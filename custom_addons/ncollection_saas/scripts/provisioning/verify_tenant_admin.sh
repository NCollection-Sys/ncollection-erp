#!/usr/bin/env bash
# shellcheck disable=SC2015
# ============================================================================
#  Tenant Administration (users, roles, administrator password) — end-to-end proof against a REAL tenant database
#  (local; heavy — not CI)
# ============================================================================
#  Needs the routing stack (db_filter=^%d$ on :8069) and a platform DB with ncollection_saas installed, the odoo
#  container carrying NC_CONFIG_SYNC_KEY. Proves, with a really provisioned tenant and real HTTP:
#    1  an unauthorised platform administrator cannot reach the tenant's users (nothing is sent),
#    2  the Tenant Administrator is identified in the user list; the platform lists the tenant's users and roles,
#    3  resetting the administrator's password inside the tenant: the temporary password WORKS on the tenant's login,
#       the first request after it is sent to the change page, a new password lifts that, the old one stops working,
#    4  the password was never stored on the platform (no row of any platform table holds it), and the tenant stores only
#       a hash; the tenant's audit log names the platform administrator and carries no secret,
#    5  creating a user works inside the tenant, within the plan's user limit (one over is refused),
#    6  roles change real groups in the tenant; the last Administrator cannot be removed or deactivated,
#    7  the service channel refuses anything but the fixed contract (malformed key, unknown role, platform's own accounts).
#  Passwords are generated by the tenant and compared inside the shell; none is printed.
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/../../../.."   # repo root

PLATFORM_DB="${PLATFORM_DB:-saastest}"
DB="tadmina"
DC=(docker compose)
DBARGS=(--db_host=db --db_user=odoo --db_password=odoo)
BASE_DOMAIN="ncollectionerp.com"
EDGE="http://127.0.0.1:8069"
pass=0; fail=0
ok(){ echo "  ✅ PASS: $1"; pass=$((pass + 1)); }
no(){ echo "  ❌ FAIL: $1"; fail=$((fail + 1)); }
hr(){ echo "----------------------------------------------------------------------"; }
wpath(){ cygpath -m "$1" 2>/dev/null || echo "$1"; }   # curl on Windows needs a native path to read a file
tq(){ "${DC[@]}" exec -T db psql -U odoo -d "$1" -tAc "$2" 2>/dev/null | tr -d '\r'; }
drop_db(){ "${DC[@]}" exec -T db psql -U odoo -d postgres -c \
  "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname='$1'" >/dev/null 2>&1 || true
  "${DC[@]}" exec -T db psql -U odoo -d postgres -c "DROP DATABASE IF EXISTS $1" >/dev/null 2>&1 || true; }
shellp(){ "${DC[@]}" exec -T odoo odoo shell -d "$PLATFORM_DB" --no-http --log-level=error "${DBARGS[@]}" 2>/dev/null; }

echo "== preconditions =="
up=0; for _try in 1 2 3 4 5; do curl -sSf -o /dev/null --max-time 10 "$EDGE/web/health" && { up=1; break; }; sleep 3; done
if [ "$up" != 1 ]; then
  echo "REFUSING: the odoo server is not reachable on :8069." >&2; exit 2; fi
echo "  syncing $PLATFORM_DB schema with the code (odoo -u ncollection_saas) ..."
_log="$(mktemp)"
if ! "${DC[@]}" exec -T odoo odoo -d "$PLATFORM_DB" -u ncollection_subscription,ncollection_saas \
     --stop-after-init --no-http --log-level=warn "${DBARGS[@]}" >"$_log" 2>&1; then
  echo "REFUSING: could not upgrade ncollection_saas on '$PLATFORM_DB' (log: $_log)." >&2; exit 1; fi
rm -f "$_log"

echo "== cleanup any prior run =="
drop_db "$DB"
shellp <<PY || true
try:
    env['ncollection.subscription'].search([('tenant_id.database_name','=','$DB')]).unlink()
    env['ncollection.tenant'].search([('database_name','=','$DB')]).unlink()
    env['res.users'].with_context(active_test=False).search([('login','in',['tapadmin','taother'])]).unlink()
    env.cr.commit()
except Exception as e:
    print('cleanup skipped:', e)
PY

echo "== provision one tenant (plan: account, 6 users) and two platform administrators =="
PLAN="TADM$$"
"${DC[@]}" exec -T odoo odoo shell -d "$PLATFORM_DB" --no-http --log-level=warn "${DBARGS[@]}" <<PY 2>/dev/null
group = env.ref('ncollection_subscription.group_platform_admin')
internal = env.ref('base.group_user')
users = {}
for login, name in (('tapadmin', 'TA Platform Admin'), ('taother', 'TA Other Platform Admin')):
    users[login] = env['res.users'].create({'name': name, 'login': login, 'group_ids': [(6, 0, [internal.id, group.id])]})
plan = env['ncollection.subscription.plan'].create({
    'name': 'Tenant admin proof', 'code': '$PLAN', 'allowed_module_names': 'account', 'max_users': 6})
env['ir.config_parameter'].sudo().set_param('ncollection_saas.provisioning_quota_per_hour', '0')
tenant = env['ncollection.tenant'].create({
    'company_name': 'Tenant Admin Co', 'database_name': '$DB', 'email': '$DB@entry.example', 'admin_login': '${DB}adm',
    'plan_id': plan.id, 'status': 'trial', 'platform_admin_ids': [(6, 0, users['tapadmin'].ids)]})
sub = env['ncollection.subscription'].create({'name': 'SUB', 'tenant_id': tenant.id, 'plan_id': plan.id, 'status': 'draft'})
tenant.subscription_id = sub.id
job = env['ncollection.provisioning.job'].create({'tenant_id': tenant.id, 'database_name': '$DB'})
env.cr.commit()
job.action_run_sync()
env.cr.commit()
print('PROVISIONED', '$DB', job.status, tenant.database_status)
PY
hr

# A small helper kept in ONE place: run python as a platform administrator against the tenant record. The password the
# tenant generates never leaves the shell: it is checked there and only booleans are printed.
tenant_py(){ shellp <<PY
import json
tenant = env['ncollection.tenant'].search([('database_name', '=', '$DB')])
def as_user(login):
    return tenant.with_user(env['res.users'].search([('login', '=', login)]))
$1
PY
}

echo "== 1. who may reach the tenant's users =="
OUT="$(tenant_py "
from odoo.exceptions import AccessError
try:
    as_user('taother').action_open_users()
    print('OTHER', 'reached')
except AccessError:
    print('OTHER', 'refused')
")"
echo "$OUT" | grep -q "OTHER refused" && ok "a platform admin who is not on the allow-list is refused" || no "unauthorised admin was not refused: $OUT"
hr

echo "== 2. the user list names the Tenant Administrator and the roles are the tenant's =="
OUT="$(tenant_py "
reply = as_user('tapadmin')._nc_admin_call('list_users')
rows = {r['login']: r for r in reply['users']}
adm = rows.get('${DB}adm')
print('ADMIN_FOUND', bool(adm), 'ADMIN_IS_ADMINISTRATOR', bool(adm and adm['administrator']), 'LIMIT', reply['max_users'])
print('NO_SERVICE_ACCOUNTS', not any(l.endswith('@ncollection.internal') or l.startswith('platform.') for l in rows))
roles = {r['code']: r for r in as_user('tapadmin')._nc_admin_call('list_roles')['roles']}
print('ROLES', 'administrator' in roles, roles['inventory_user']['available'] is False, roles['accountant']['available'])
")"
echo "$OUT" | grep -q "ADMIN_FOUND True ADMIN_IS_ADMINISTRATOR True LIMIT 6" && ok "the tenant administrator is listed, as an administrator, with the plan limit" || no "admin listing wrong: $OUT"
echo "$OUT" | grep -q "NO_SERVICE_ACCOUNTS True" && ok "service and proxy accounts are not listed" || no "service accounts leaked into the list: $OUT"
echo "$OUT" | grep -q "ROLES True True True" && ok "roles reflect the tenant's installed applications (Accounting yes, Inventory no)" || no "role availability wrong: $OUT"
hr

echo "== 3. reset the administrator password inside the tenant and use it =="
# The password stays in a shell variable and a 0600 temp file (read by the curl calls below), removed straight after;
# it is never echoed.
PWFILE="$(mktemp)"; chmod 600 "$PWFILE"
OUT="$(tenant_py "
import re
reply = as_user('tapadmin')._nc_admin_call('list_users')
admin = next(r for r in reply['users'] if r['login'] == '${DB}adm')
dialog = env['ncollection.tenant.user.password'].with_user(env['res.users'].search([('login', '=', 'tapadmin')])).create({
    'tenant_id': tenant.id, 'remote_id': admin['id'], 'user_name': admin['name']})
message = dialog.action_apply()['params']['message']
env.cr.commit()
print('PW=' + (re.search(r'Temporary password for .*?: (\\S+)  -', message) or [None, ''])[1])
")"
TEMP_PW="$(printf '%s\n' "$OUT" | sed -n 's/^PW=//p' | tr -d '\r')"
printf '%s' "$TEMP_PW" > "$PWFILE"
[ "${#TEMP_PW}" -ge 16 ] && ok "the tenant generated a temporary password (16+ characters)" || no "no temporary password was generated"
JAR="$(mktemp)"
login_code(){   # login_code <login> <password-file> -> HTTP status of the sign-in POST
  local csrf
  csrf="$(curl -s -c "$JAR" -b "$JAR" -H "Host: $DB.$BASE_DOMAIN" "$EDGE/web/login" | sed -n 's/.*name="csrf_token" value="\([^"]*\)".*/\1/p' | head -1)"
  curl -s -o /dev/null -w "%{http_code}" -c "$JAR" -b "$JAR" -H "Host: $DB.$BASE_DOMAIN" \
    --data-urlencode "csrf_token=$csrf" --data-urlencode "login=$1" --data-urlencode "password@$(wpath "$2")" "$EDGE/web/login"
}
[ "$(login_code "${DB}adm" "$PWFILE")" = "303" ] && ok "the temporary password signs in to the tenant" || no "temporary password did not sign in"
LOC="$(curl -s -o /dev/null -w "%{redirect_url}" -b "$JAR" -H "Host: $DB.$BASE_DOMAIN" "$EDGE/odoo" || true)"
echo "$LOC" | grep -q "/ncollection/password/change" && ok "the first page after it is the change-password page" || no "not sent to the change page ($LOC)"
RPC="$(curl -s -b "$JAR" -H "Host: $DB.$BASE_DOMAIN" -H 'Content-Type: application/json' \
  -d '{"jsonrpc":"2.0","method":"call","params":{"model":"res.partner","method":"search_count","args":[[]],"kwargs":{}}}' \
  "$EDGE/web/dataset/call_kw/res.partner/search_count")"
echo "$RPC" | grep -q "choose a new password" && ok "the RPC routes are refused until it is changed" || no "RPC was not refused: $RPC"
CSRF="$(curl -s -b "$JAR" -c "$JAR" -H "Host: $DB.$BASE_DOMAIN" "$EDGE/ncollection/password/change" | sed -n 's/.*name="csrf_token" value="\([^"]*\)".*/\1/p' | head -1)"
NEWPW="Nn2!$(head -c 12 /dev/urandom | base64 | tr -d '/+=' | head -c 14)"
CODE="$(curl -s -o /dev/null -w "%{http_code}" -b "$JAR" -c "$JAR" -H "Host: $DB.$BASE_DOMAIN" \
  --data-urlencode "csrf_token=$CSRF" --data-urlencode "old_password@$(wpath "$PWFILE")" --data-urlencode "password=$NEWPW" \
  --data-urlencode "confirm_password=$NEWPW" "$EDGE/ncollection/password/change")"
[ "$CODE" = "303" ] && ok "choosing a new password succeeds and ends the session" || no "password change failed ($CODE)"
NEWFILE="$(mktemp)"; chmod 600 "$NEWFILE"; printf '%s' "$NEWPW" > "$NEWFILE"
[ "$(login_code "${DB}adm" "$NEWFILE")" = "303" ] && ok "the chosen password signs in" || no "chosen password did not sign in"
LOC="$(curl -s -o /dev/null -w "%{redirect_url}" -b "$JAR" -H "Host: $DB.$BASE_DOMAIN" "$EDGE/odoo" || true)"
echo "$LOC" | grep -q "password/change" && no "still forced to change after choosing" || ok "no longer sent to the change page"
[ "$(login_code "${DB}adm" "$PWFILE")" = "200" ] && ok "the temporary password no longer works" || no "temporary password still works"
hr

echo "== 4. nothing stored where it must not be =="
HASHED="$(tq "$DB" "SELECT count(*) FROM res_users WHERE login='${DB}adm' AND password IS NOT NULL AND password <> '$TEMP_PW' AND password <> '$NEWPW'")"
[ "$HASHED" = "1" ] && ok "the tenant stores a hash, not the password" || no "password column not a hash"
LEAK_T="$(tq "$DB" "SELECT count(*) FROM ncollection_auth_log WHERE coalesce(detail,'') || coalesce(login,'') || coalesce(actor_ref,'') LIKE '%' || '$TEMP_PW' || '%'")"
[ "$LEAK_T" = "0" ] && ok "the tenant's audit log carries no password" || no "password found in the tenant audit log"
AUD="$(tq "$DB" "SELECT count(*) FROM ncollection_auth_log WHERE event_type='admin_password_reset' AND actor_ref LIKE 'platform:u%TA Platform Admin%'")"
[ "$AUD" -ge 1 ] && ok "the tenant's audit log names the platform administrator" || no "no platform administrator in the tenant audit log"
LEAK_P="$(tq "$PLATFORM_DB" "SELECT count(*) FROM mail_message WHERE body LIKE '%' || '$TEMP_PW' || '%' OR body LIKE '%' || '$NEWPW' || '%'")"
[ "$LEAK_P" = "0" ] && ok "the platform chatter carries no password" || no "password found in the platform chatter"
NOTE="$(tq "$PLATFORM_DB" "SELECT count(*) FROM mail_message m JOIN ncollection_tenant t ON t.id=m.res_id AND m.model='ncollection.tenant' WHERE t.database_name='$DB' AND m.body LIKE '%reset the password%'")"
[ "$NOTE" -ge 1 ] && ok "the platform records that a reset happened, and who did it" || no "no platform note about the reset"
# every text column of every transient table the dialogs use: none holds a password
LEAK_W="$(tq "$PLATFORM_DB" "SELECT coalesce((SELECT count(*) FROM ncollection_tenant_user_password WHERE new_password IS NOT NULL),0)")"
[ "$LEAK_W" = "0" ] && ok "the dialog row holds no typed password" || no "a typed password is still in a dialog row"
rm -f "$PWFILE" "$NEWFILE" "$JAR"
unset TEMP_PW NEWPW
hr

echo "== 5/6. creating users within the plan limit; roles are real groups; the last Administrator stays =="
# seats already taken in the tenant (the admin and its service accounts count, as the plan limit counts them)
USED="$(tq "$DB" "SELECT count(*) FROM res_users WHERE active AND NOT share AND NOT coalesce(nc_platform_proxy, false)")"
ROOM=$((6 - USED))
OUT="$(tenant_py "
from odoo.exceptions import UserError, ValidationError, AccessError
svc = as_user('tapadmin')
made = []
for i in range(1, 9):
    try:
        r = svc._nc_admin_call('create_user', {'name': 'TA User %d' % i, 'login': 'tauser%d' % i, 'role_codes': ['accountant']})
        made.append(r['user_id'])
    except UserError as e:
        print('LIMIT_HIT_AT', i, 'maximum of 6' in str(e))
        break
print('CREATED', len(made))
users = {r['login']: r for r in svc._nc_admin_call('list_users')['users']}
print('ACCOUNTANT_ROLE', users['tauser1']['role_codes'], users['tauser1']['must_change_password'])
")"
echo "$OUT" | grep -q "LIMIT_HIT_AT $((ROOM + 1)) True" && ok "the plan's user limit (6) stops the first user over it" || no "limit behaviour wrong (room $ROOM): $OUT"
echo "$OUT" | grep -q "CREATED $ROOM$" && ok "exactly the seats still free were filled ($ROOM)" || no "creation count wrong: $OUT"
echo "$OUT" | grep -q "ACCOUNTANT_ROLE \['accountant'\] True" && ok "the role applied and the user must change the temporary password" || no "role or flag wrong: $OUT"
G="$(tq "$DB" "SELECT count(*) FROM res_groups_users_rel r JOIN res_users u ON u.id=r.uid JOIN ir_model_data d ON d.res_id=r.gid AND d.model='res.groups' WHERE u.login='tauser1' AND d.module='ncollection_core' AND d.name='group_role_accountant'")"
[ "$G" = "1" ] && ok "the Accountant role is a real Odoo group (ncollection_core.group_role_accountant) held by the user in the tenant" || no "role did not become a real group"
OUT="$(tenant_py "
from odoo.exceptions import UserError, ValidationError
svc = as_user('tapadmin')
rows = {r['login']: r for r in svc._nc_admin_call('list_users')['users']}
aid = rows['${DB}adm']['id']
for label, call in (
    ('DEACTIVATE_LAST', lambda: svc._nc_admin_call('set_active', {'user_id': aid, 'active': False})),
    ('REMOVE_LAST', lambda: svc._nc_admin_call('set_roles', {'user_id': aid, 'role_codes': []})),
    ('UNKNOWN_ROLE', lambda: svc._nc_admin_call('set_roles', {'user_id': rows['tauser1']['id'], 'role_codes': ['no_such_role']})),
    ('BAD_KEY', lambda: svc._nc_admin_call('reset_password', {'user_id': rows['tauser1']['id'], 'group_ids': [1]})),
    ('SYSTEM_USER', lambda: svc._nc_admin_call('reset_password', {'user_id': 1})),
):
    try:
        call(); print(label, 'allowed')
    except UserError:
        print(label, 'refused')
")"
for what in DEACTIVATE_LAST REMOVE_LAST UNKNOWN_ROLE BAD_KEY SYSTEM_USER; do
  echo "$OUT" | grep -q "$what refused" && ok "$what refused by the tenant" || no "$what was not refused: $OUT"
done
hr

echo "== 7. editing a user (name and email only) acts on the tenant =="
OUT="$(tenant_py "
rows = {r['login']: r for r in as_user('tapadmin')._nc_admin_call('list_users')['users']}
dialog = env['ncollection.tenant.user.edit'].with_user(env['res.users'].search([('login', '=', 'tapadmin')])).create({
    'tenant_id': tenant.id, 'remote_id': rows['tauser1']['id'], 'name': 'TA Renamed', 'email': 'ta.renamed@example.com'})
dialog.action_apply()
env.cr.commit()
print('EDITED')
")"
echo "$OUT" | grep -q EDITED && ok "the edit dialog went through" || no "edit dialog failed: $OUT"
[ "$(tq "$DB" "SELECT count(*) FROM res_users u JOIN res_partner p ON p.id=u.partner_id WHERE u.login='tauser1' AND p.name='TA Renamed' AND p.email='ta.renamed@example.com'")" = "1" ] && ok "the tenant's user carries the new name and email, same login" || no "edit did not reach the tenant"
[ "$(tq "$DB" "SELECT count(*) FROM ncollection_auth_log WHERE event_type='admin_user_update' AND actor_ref LIKE 'platform:u%'")" -ge 1 ] && ok "the edit is in the tenant's audit log with the platform administrator" || no "edit not audited"
hr

echo "== cleanup =="
drop_db "$DB"
shellp <<PY || true
env['ncollection.subscription'].search([('tenant_id.database_name','=','$DB')]).unlink()
env['ncollection.tenant'].search([('database_name','=','$DB')]).unlink()
env['res.users'].with_context(active_test=False).search([('login','in',['tapadmin','taother'])]).unlink()
env.cr.commit()
PY
echo "============================================================"
echo "RESULT: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
